/// Prepares the q-independent public relation for
/// `2^log_compressions` independent SHA-256 compression invocations at the
/// DEFAULT security profile, [`Lambda100`] (no grinding anywhere; every
/// term this crate controls ≥ 100 bits). Use
/// [`prepare_sha256_compression_batch_with_profile`] to select
/// `Lambda128` or the historical `Sha128ReferenceSchedule`.
/// Supported exponents are [`SHA256_MIN_LOG_COMPRESSIONS`] through
/// [`SHA256_MAX_LOG_COMPRESSIONS`], inclusive.
/// Batches smaller than `2^7` use the packed inner sumcheck because the
/// local-major product opening requires at least 128 instance rows.
///
/// No runtime modulus is consulted here. The proof flow commits to the Bit
/// source rows before deriving `q` and internally projecting this relation.
pub fn prepare_sha256_compression_batch(
    log_compressions: usize,
) -> Result<PreparedSha256CompressionBatch, Sha256ConstraintError> {
    prepare_sha256_compression_batch_with_profile::<Lambda100>(log_compressions)
}

/// [`prepare_sha256_compression_batch`] under an explicit
/// single-prime security profile: the profile's interval and grinding
/// schedule are instantiated here and drive the whole prove/verify path.
pub fn prepare_sha256_compression_batch_with_profile<P: IopSecurityProfile>(
    log_compressions: usize,
) -> Result<PreparedSha256CompressionBatch, Sha256ConstraintError> {
    prepare_sha256_compression_batch_with_profile_and_layout::<P>(
        log_compressions,
        Sha256OpeningLayout::Default,
    )
}

/// [`prepare_sha256_compression_batch_with_profile`] with an explicit
/// assignment layout for the BitZ opening (see [`Sha256OpeningLayout`]).
pub fn prepare_sha256_compression_batch_with_profile_and_layout<P: IopSecurityProfile>(
    log_compressions: usize,
    layout: Sha256OpeningLayout,
) -> Result<PreparedSha256CompressionBatch, Sha256ConstraintError> {
    // Gate the profile's opener target before any construction: the Ligerito
    // solver itself errors on out-of-range targets since the rate-1/2 default
    // work, which would otherwise mask this dedicated error.
    if !(64..=128).contains(&P::LIGERITO_TARGET_BITS) {
        return Err(Sha256ConstraintError::UnsupportedLigeritoTargetBits {
            actual: P::LIGERITO_TARGET_BITS,
        });
    }
    let instances = validate_batch_exponent(log_compressions)?;
    validate_instance_capacity(instances)?;
    let layout = if layout == Sha256OpeningLayout::Default && log_compressions < LOG_PACKING {
        let assignment_vars = packed_domain_vars(instances, SHA256_H_INSTANCE_BITS)?;
        Sha256OpeningLayout::InnerSumcheck {
            row_vars: single_forest_binary_params(assignment_vars).row_vars,
        }
    } else {
        layout
    };
    let prepared =
        prepare_sha256_compression_instances_with_profile_and_layout::<P>(instances, layout)?;
    let selection = crate::ligerito_flock::LigeritoSelection::for_target(
        prepared.security.ligerito_target_bits,
    );
    let prepared = prepared.with_ligerito(selection)?;
    validate_prepared_protocol(&prepared)?;
    Ok(prepared)
}

/// Controlled `2^14`-compression geometry used by the fixed-98-bit `t,s`
/// sweep. This is intentionally feature-gated and does not change the
/// production transcript-derived-prime profile.
#[cfg(feature = "bench-internals")]
pub fn prepare_sha256_compression_batch_for_product_t_fixed98(
    log_compressions: usize,
    product_t: usize,
) -> Result<PreparedSha256CompressionBatch, Sha256ConstraintError> {
    if log_compressions != 14 || !(LOG_PACKING..=28).contains(&product_t) {
        return Err(Sha256ConstraintError::UnsupportedProductSweepGeometry {
            log_compressions,
            t: product_t,
        });
    }
    let instances = validate_batch_exponent(log_compressions)?;
    let prepared = prepare_sha256_compression_instances(
        instances,
        Sha256OpeningLayout::Default,
        Some(product_t),
        |_| Ok(fixed_98_security_params()),
        true,
    )?;
    let selection = crate::ligerito_flock::LigeritoSelection::for_target(
        prepared.security.ligerito_target_bits,
    );
    let prepared = prepared.with_ligerito(selection)?;
    validate_prepared_protocol(&prepared)?;
    if u128::from(*prepared.max_boolean_residual_bound()) >= SHA256_FIXED_98_PRIME {
        return Err(Sha256ConstraintError::FixedPrimeResidualBound);
    }
    Ok(prepared)
}

/// Prepares the largest packed batch whose assignment witness fits exactly
/// inside `2^log_assignment_rows` cells.
///
/// Each compression contributes [`SHA256_H_INSTANCE_BITS`] cells and the
/// entire batch shares one leading constant cell.  Any unused cells form one
/// trailing zero suffix; there is no per-instance padding. The resulting
/// next-power-of-two instance capacity must lie in the same supported window
/// as [`prepare_sha256_compression_batch`].
pub fn prepare_sha256_compression_batch_for_assignment_rows(
    log_assignment_rows: usize,
) -> Result<PreparedSha256CompressionBatch, Sha256ConstraintError> {
    prepare_sha256_compression_batch_for_assignment_rows_with_profile::<Lambda100>(
        log_assignment_rows,
    )
}

/// [`prepare_sha256_compression_batch_for_assignment_rows`] under an explicit
/// security profile.
pub fn prepare_sha256_compression_batch_for_assignment_rows_with_profile<P: IopSecurityProfile>(
    log_assignment_rows: usize,
) -> Result<PreparedSha256CompressionBatch, Sha256ConstraintError> {
    let rows = 1usize
        .checked_shl(
            u32::try_from(log_assignment_rows)
                .map_err(|_| Sha256ConstraintError::InvalidBatchExponent)?,
        )
        .ok_or(Sha256ConstraintError::InvalidBatchExponent)?;
    let instances = rows
        .checked_sub(1)
        .ok_or(Sha256ConstraintError::InvalidBatchExponent)?
        / SHA256_H_INSTANCE_BITS;
    if instances == 0 {
        return Err(Sha256ConstraintError::InvalidBatchExponent);
    }
    validate_instance_capacity(instances)?;
    let prepared = prepare_sha256_compression_instances_with_profile::<P>(instances)?;
    let selection = crate::ligerito_flock::LigeritoSelection::for_target(
        prepared.security.ligerito_target_bits,
    );
    let prepared = prepared.with_ligerito(selection)?;
    validate_prepared_protocol(&prepared)?;
    if prepared.h_layout.row_vars + prepared.h_layout.col_vars != log_assignment_rows {
        return Err(Sha256ConstraintError::InvalidBatchExponent);
    }
    Ok(prepared)
}

