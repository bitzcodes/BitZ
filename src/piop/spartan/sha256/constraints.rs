/// Live Bit source bits generated by one compression.
pub const SHA256_F_LIVE_BITS: usize = 7_144;
/// Source bits after adding the public constant-one coordinate.
pub const SHA256_F_BAR_LIVE_BITS: usize = SHA256_F_LIVE_BITS + 1;
/// Per-compression source width after removing the shared constant cell.
pub const SHA256_F_INSTANCE_BITS: usize = SHA256_F_BAR_LIVE_BITS - 1;
/// Live integer-assignment bits, including its leading constant one.
pub const SHA256_H_BAR_LIVE_BITS: usize = 20_457;
/// Per-compression assignment width after removing the shared constant cell.
pub const SHA256_H_INSTANCE_BITS: usize = SHA256_H_BAR_LIVE_BITS - 1;
/// Number of public words in one compression statement: state, block, output.
pub(crate) const SHA256_PUBLIC_WORDS: usize = 32;
/// Bit width of every public SHA-256 word.
pub(crate) const SHA256_PUBLIC_WORD_BITS: usize = 32;
/// Returns the local integer-assignment column for one public statement bit.
///
/// Word slots use canonical statement order: state `[0, 8)`, block `[8, 24)`,
/// then output `[24, 32)`. Bits within each word are least-significant first.
pub(crate) const fn sha256_public_h_column(word_slot: usize, bit: usize) -> usize {
    assert!(word_slot < SHA256_PUBLIC_WORDS);
    assert!(bit < SHA256_PUBLIC_WORD_BITS);

    match word_slot {
        0..8 => 1 + 32 * word_slot + bit,
        8..24 => 257 + 32 * (word_slot - 8) + bit,
        _ => 20_193 + 33 * (word_slot - 24) + bit,
    }
}

/// Returns the local committed-source column for one public statement bit.
///
/// This uses the same word and bit order as [`sha256_public_h_column`].
pub(crate) const fn sha256_public_f_column(word_slot: usize, bit: usize) -> usize {
    assert!(word_slot < SHA256_PUBLIC_WORDS);
    assert!(bit < SHA256_PUBLIC_WORD_BITS);

    match word_slot {
        0..8 => 513 + 32 * word_slot + bit,
        8..24 => 1 + 32 * (word_slot - 8) + bit,
        _ => 6_881 + 33 * (word_slot - 24) + bit,
    }
}

/// Live rank-1 constraints generated by one compression.
pub const SHA256_CONSTRAINTS: usize = 184;
/// Failures while compiling or repeating the public SHA-256 relation.
#[derive(Debug, Error)]
pub enum Sha256ConstraintError {
    /// The requested batch or packed global domain is empty or does not fit
    /// the host index type.
    #[error("SHA-256 batch geometry is invalid or too large")]
    InvalidBatchExponent,

    /// The outer instance capacity is outside the runtime-prime protocol's
    /// supported production window.
    #[error(
        "SHA-256 runtime-prime protocol requires log-instance-capacity in [4, 16], got {actual}"
    )]
    UnsupportedInstanceCapacityExponent { actual: usize },

    /// The selected security profile asks the validated UDR backend for an
    /// unsupported round-by-round target.
    #[error("SHA-256 Ligerito target must be in [64, 128] bits, got {actual}")]
    UnsupportedLigeritoTargetBits { actual: usize },

    /// The SHA virtual opening is deliberately configured to use one
    /// mod-q weight chunk, hence one merged forest.
    #[error("SHA-256 opening requires exactly one forest, got {actual}")]
    UnsupportedOpeningForestCount { actual: usize },

    /// An explicit layout asked for a row split the assignment domain does
    /// not admit (`LOG_PACKING <= t < vars` for the inner sumcheck,
    /// `15 <= t <= 15 + k` for the transposed product tensor).
    #[error(
        "SHA-256 opening layout cannot split {assignment_vars} assignment vars at {row_vars} row vars"
    )]
    InvalidOpeningRowVars {
        row_vars: usize,
        assignment_vars: usize,
    },

    /// The transposed product layout needs a power-of-two batch.
    #[error("SHA-256 transposed product layout needs a power-of-two batch, got {instances}")]
    ProductLayoutNeedsPowerOfTwoBatch { instances: usize },

    /// The selected security profile is incompatible with the single
    /// transcript-derived-prime SHA protocol.
    #[error(transparent)]
    PrimeProfile(#[from] Sha256PrimeError),

    /// Generated R1CS matrices did not prepare successfully.
    #[error(transparent)]
    Spartan(#[from] SpartanMatrixError),

    /// Generated Bit map metadata did not prepare successfully.
    #[error(transparent)]
    VirtualMap(#[from] PreparedVirtualMapError),

    /// The canonical integer-relation digest cannot encode this host shape.
    #[error("SHA-256 integer relation dimensions do not fit the canonical encoding")]
    IntegerRelationTooLarge,

    /// The security profile could not be instantiated at this shape.
    #[error(transparent)]
    Profile(#[from] ProfileError),

    #[error("invalid Ligerito configuration: {0}")]
    LigeritoConfig(String),

    /// The controlled product-layout sweep requires exactly `2^14`
    /// compressions and `7 <= t <= 28`.
    #[error(
        "unsupported SHA-256 product sweep geometry: log_compressions={log_compressions}, t={t}"
    )]
    UnsupportedProductSweepGeometry { log_compressions: usize, t: usize },

    /// The fixed field must exceed every exact Bit SHA row residual.
    #[error("the fixed 98-bit SHA prime does not exceed the exact Bit residual bound")]
    FixedPrimeResidualBound,
}

/// A q-independent SHA-256 compression relation prepared for a packed batch.
///
/// How the synthesized SHA assignment is laid out for the BitZ opening.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Sha256OpeningLayout {
    /// The production choice. Power-of-two batches of at least 128 open the
    /// product-structured residual directly, laid out as the balanced
    /// `Id_{2^r} ⊗ M` block layout: this resolves to
    /// [`Sha256OpeningLayout::ProductTransposed`] with the `row_vars` picked by
    /// `balanced_product_row_vars`, so the tensor split sits at the
    /// instantiation's `t = ceil(0.6 · n)` balance point instead of the
    /// `t = min(k, 13)` pin that put every local cell on the column axis.
    /// Smaller and non-power-of-two batches run the inner sumcheck over a
    /// balanced split capped at one forest.
    Default,
    /// Run the inner sumcheck and split the flat assignment domain as
    /// `2^row_vars` BitZ rows × `2^(vars - row_vars)` columns. Splits above
    /// the one-forest cap are allowed: the opening then carries one merged
    /// forest per mod-q weight chunk, while the read-off vector sent in the
    /// clear shrinks to `2^(vars - row_vars)` integers per chunk. The
    /// security derivation runs against the chosen split (its integer lift
    /// sums `2^t` terms, which narrows the prime interval once `t > k`).
    InnerSumcheck { row_vars: usize },
    /// Keep the direct product opening (no inner sumcheck) but lay the
    /// product tensor out instance-major, so the 15 local bits plus the low
    /// `row_vars - 15` instance bits form the `2^row_vars` BitZ rows and only
    /// the remaining high instance bits form the columns. The rank-one
    /// coefficient `eq(instance) · d[local]` factors across that split too.
    /// Power-of-two batches only; `15 ≤ row_vars ≤ 15 + k`; splits above the
    /// one-forest cap open with one forest per weight chunk.
    ProductTransposed { row_vars: usize },
}

/// The exact signed integer matrices and local Bit map are synthesized
/// once and shared by every batch. The committed source and derived assignment
/// share one constant, concatenate all live instances, and pad only their
/// complete global domains. The prover and verifier project this retained
/// relation only after the commitment-bound transcript selects a runtime prime.
#[derive(Clone, Debug)]
pub struct PreparedSha256CompressionBatch {
    local: &'static IntegerLocalRelation,
    map: PackedRepeatedVirtualMap,
    product_map: Option<PackedSourceRepeatedVirtualMap>,
    product_p_h: Option<IntegerMatrixLayout>,
    f_layout: IntegerMatrixLayout,
    h_layout: IntegerMatrixLayout,
    instances: usize,
    log_instance_capacity: usize,
    security: IopSecurityParams,
    ligerito: Option<crate::ligerito_flock::ResolvedLigerito>,
    prime_profile: Sha256PrimeProfile,
    opening_layout: Sha256OpeningLayout,
}

impl PreparedSha256CompressionBatch {
    /// Select only this batch's Ligerito opener; the enclosing target is retained.
    pub fn with_ligerito(
        mut self,
        selection: crate::ligerito_flock::LigeritoSelection,
    ) -> Result<Self, Sha256ConstraintError> {
        let resolved = selection
            .resolve(
                self.f_layout.row_vars + self.f_layout.col_vars - LOG_PACKING,
                self.security.ligerito_target_bits,
            )
            .map_err(Sha256ConstraintError::LigeritoConfig)?;
        self.security.adopt_ood_round(resolved.ood_bits())?;
        self.ligerito = Some(resolved);
        Ok(self)
    }

    pub fn ligerito_configuration(
        &self,
    ) -> Result<&crate::ligerito_flock::ResolvedLigerito, Sha256ConstraintError> {
        self.ligerito.as_ref().ok_or_else(|| {
            Sha256ConstraintError::LigeritoConfig(
                "test-only preparation has no production Ligerito policy".into(),
            )
        })
    }

    /// The assignment layout this batch was prepared with.
    pub const fn opening_layout(&self) -> Sha256OpeningLayout {
        self.opening_layout
    }

    /// BitZ geometry the opening runs against: the product view under the
    /// direct product opening, the packed assignment otherwise.
    pub fn opening_params(&self) -> &IntegerMatrixLayout {
        self.product_p_h.as_ref().unwrap_or(&self.h_layout)
    }

    /// Exact unpadded signed linear relation generated by the SHA circuit.
    ///
    /// The circuit emits its zero assertions as `0 * 0 = C h_bar`, so its
    /// generated R1CS `A` and `B` matrices are empty and this matrix is the
    /// original `C`. It has exactly [`SHA256_CONSTRAINTS`] rows and
    /// [`SHA256_H_BAR_LIVE_BITS`] columns.
    pub(crate) const fn linear_relation(&self) -> &Sha256LinearRelation {
        &self.local.linear_relation
    }

    /// Projects [`Self::linear_relation`] into the selected runtime field.
    #[allow(dead_code)]
    pub(crate) fn project_linear_relation(
        &self,
        field_config: &<SpartanBitzField as crate::piop::spartan::SpartanField>::Config,
    ) -> Result<PreparedSha256LinearRelation, Sha256ConstraintError> {
        self.local.linear_relation.project(field_config)
    }

    /// Flattens one live local constraint row in instance-major order.
    ///
    /// Unlike the compatibility R1CS path, this exact linear layout does not
    /// insert a 256-row block for each instance.
    #[allow(dead_code)]
    pub(crate) fn flat_constraint_row(&self, instance: usize, local_row: usize) -> Option<usize> {
        (instance < self.instances && local_row < SHA256_CONSTRAINTS)
            .then(|| instance * SHA256_CONSTRAINTS + local_row)
    }

    /// Flattens one local assignment column into the packed batch assignment.
    ///
    /// Local column zero is the one constant cell shared by every instance.
    /// Every other local column is placed immediately after the preceding
    /// instance, with no per-instance power-of-two padding.
    #[allow(dead_code)]
    pub(crate) fn flat_assignment_column(
        &self,
        instance: usize,
        local_column: usize,
    ) -> Option<usize> {
        if instance >= self.instances || local_column >= SHA256_H_BAR_LIVE_BITS {
            return None;
        }
        Some(if local_column == 0 {
            0
        } else {
            1 + instance * SHA256_H_INSTANCE_BITS + local_column - 1
        })
    }

    /// Number of live rows in the flat linear relation batch.
    #[allow(dead_code)]
    pub(crate) const fn linear_row_count(&self) -> usize {
        self.instances * SHA256_CONSTRAINTS
    }

    /// Number of live columns in the packed assignment shared by the batch.
    pub(crate) const fn linear_assignment_column_count(&self) -> usize {
        1 + self.instances * SHA256_H_INSTANCE_BITS
    }

    /// Canonical digest of the exact integer matrices and local Bit map.
    pub const fn integer_relation_digest(&self) -> &[u8; 32] {
        &self.local.digest
    }

    /// Repeated Bit map for the complete compression batch.
    pub const fn map(&self) -> &PackedRepeatedVirtualMap {
        &self.map
    }

    /// Proof-only local-column × instance view used to open the complete
    /// product-structured SHA residual directly. It is available exactly when
    /// the number of instances is a power of two.
    pub(crate) const fn product_map(&self) -> Option<&PackedSourceRepeatedVirtualMap> {
        self.product_map.as_ref()
    }

    /// BitZ geometry of the proof-only product assignment view.
    pub const fn product_assignment_params(&self) -> Option<&IntegerMatrixLayout> {
        self.product_p_h.as_ref()
    }

    /// Stable label for the proof-only product tensor ordering.
    pub fn product_layout_name(&self) -> Option<&'static str> {
        self.product_map.as_ref().map(|map| match map.order() {
            PackedSourceOrder::LocalMajor => "instance_rows",
            PackedSourceOrder::InstanceMajor => "local_rows",
        })
    }

    /// Number of live independent compression instances.
    pub const fn instances(&self) -> usize {
        self.instances
    }

    /// Logarithm of the power-of-two outer Spartan instance capacity.
    pub const fn log_instance_capacity(&self) -> usize {
        self.log_instance_capacity
    }

    /// BitZ geometry of the committed Bit source rows.
    pub const fn source_params(&self) -> &IntegerMatrixLayout {
        &self.f_layout
    }

    /// BitZ geometry of the synthesized Bit assignment rows.
    pub const fn assignment_params(&self) -> &IntegerMatrixLayout {
        &self.h_layout
    }

    /// Conservative maximum of
    /// `sum(|A_i|) sum(|B_i|) + sum(|C_i|)` over local constraint rows.
    /// For a Bit assignment this bounds the magnitude of every exact
    /// integer R1CS residual before reduction modulo q.
    pub fn max_boolean_residual_bound(&self) -> &field::Uint<2> {
        &self.local.max_boolean_residual_bound
    }

    /// The instantiated security parameters and their accounting.
    pub const fn security(&self) -> &IopSecurityParams {
        &self.security
    }

    pub(super) const fn prime_profile(&self) -> Sha256PrimeProfile {
        self.prime_profile
    }
}

/// Exact q-independent signed linear relation for one SHA compression.
///
/// This is the generated circuit's original `C` matrix, before either the row
/// domain or assignment domain is padded for the compatibility R1CS prover.
#[derive(Clone, Debug, Eq, PartialEq)]
pub(crate) struct Sha256LinearRelation {
    native_matrix: CscMatrix<Box<[i64]>>,
}

impl Sha256LinearRelation {
    /// Exact signed matrix in canonical CSC form.
    #[allow(dead_code)]
    pub(crate) const fn matrix(&self) -> &CscMatrix<Box<[i64]>> {
        &self.native_matrix
    }

    /// Exact coefficients in the native type used by the small-value prover.
    pub(crate) const fn native_matrix(&self) -> &CscMatrix<Box<[i64]>> {
        &self.native_matrix
    }

    /// Number of live local constraint rows (184).
    #[allow(dead_code)]
    pub(crate) const fn row_count(&self) -> usize {
        self.native_matrix.row_count()
    }

    /// Number of live local assignment columns (20,457).
    #[allow(dead_code)]
    pub(crate) const fn column_count(&self) -> usize {
        self.native_matrix.column_count()
    }

    /// Number of signed nonzero coefficients.
    #[allow(dead_code)]
    pub(crate) const fn nnz(&self) -> usize {
        self.native_matrix.nnz()
    }

    /// Projects the exact signed coefficients into a validated runtime field.
    #[allow(dead_code)]
    pub(crate) fn project(
        &self,
        field_config: &<SpartanBitzField as crate::piop::spartan::SpartanField>::Config,
    ) -> Result<PreparedSha256LinearRelation, Sha256ConstraintError> {
        validate_sha256_field_config(field_config)?;
        let matrix = project_signed_matrix(&self.native_matrix, field_config)?;
        Ok(PreparedSha256LinearRelation {
            matrix,
            field_config: field_config.clone(),
        })
    }
}

