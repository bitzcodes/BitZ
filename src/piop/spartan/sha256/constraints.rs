fn prepare_sha256_compression_instances(
    instances: usize,
    mut layout: Sha256OpeningLayout,
    requested_product_t: Option<usize>,
    make_security: impl FnOnce(
        &super::super::profile::IopInstanceFacts,
    ) -> Result<IopSecurityParams, Sha256ConstraintError>,
    fixed_98: bool,
) -> Result<PreparedSha256CompressionBatch, Sha256ConstraintError> {
    let log_instance_capacity = instances
        .checked_next_power_of_two()
        .ok_or(Sha256ConstraintError::InvalidBatchExponent)?
        .ilog2() as usize;
    let exponent = u32::try_from(log_instance_capacity)
        .map_err(|_| Sha256ConstraintError::InvalidBatchExponent)?;
    let local = integer_local_relation();
    let source_vars = packed_domain_vars(instances, SHA256_F_INSTANCE_BITS)?;
    let assignment_vars = packed_domain_vars(instances, SHA256_H_INSTANCE_BITS)?;
    let f_layout = balanced_binary_params(source_vars);
    let local_bits = SHA256_H_BAR_LIVE_BITS.next_power_of_two().ilog2() as usize;
    // The production default opens the balanced `Id_{2^r} ⊗ M` block layout.
    // Resolving it here, before the geometry match, keeps the lift-arity and
    // forest-count rules below reading the layout that is actually opened.
    // The `t,s` sweep supplies its own split, so it keeps the legacy geometry.
    if layout == Sha256OpeningLayout::Default
        && requested_product_t.is_none()
        && instances.is_power_of_two()
    {
        layout = Sha256OpeningLayout::ProductTransposed {
            row_vars: balanced_product_row_vars(assignment_vars, local_bits, log_instance_capacity),
        };
    }
    let (h_layout, mut product_p_h, mut product_order) = match layout {
        Sha256OpeningLayout::Default => (
            single_forest_binary_params(assignment_vars),
            instances.is_power_of_two().then(|| {
                let t = log_instance_capacity.min(13);
                IntegerMatrixLayout {
                    row_vars: t,
                    col_vars: assignment_vars - t,
                    word_bits: 1,
                }
            }),
            PackedSourceOrder::LocalMajor,
        ),
        Sha256OpeningLayout::ProductTransposed { row_vars } => {
            if !instances.is_power_of_two() {
                return Err(Sha256ConstraintError::ProductLayoutNeedsPowerOfTwoBatch { instances });
            }
            if row_vars < local_bits || row_vars > local_bits + log_instance_capacity {
                return Err(Sha256ConstraintError::InvalidOpeningRowVars {
                    row_vars,
                    assignment_vars,
                });
            }
            (
                single_forest_binary_params(assignment_vars),
                Some(IntegerMatrixLayout {
                    row_vars: row_vars,
                    col_vars: assignment_vars - row_vars,
                    word_bits: 1,
                }),
                PackedSourceOrder::InstanceMajor,
            )
        }
        Sha256OpeningLayout::InnerSumcheck { row_vars } => {
            if row_vars < LOG_PACKING || row_vars >= assignment_vars {
                return Err(Sha256ConstraintError::InvalidOpeningRowVars {
                    row_vars,
                    assignment_vars,
                });
            }
            (
                IntegerMatrixLayout {
                    row_vars: row_vars,
                    col_vars: assignment_vars - row_vars,
                    word_bits: 1,
                },
                None,
                PackedSourceOrder::LocalMajor,
            )
        }
    };
    if let Some(t) = requested_product_t {
        if !instances.is_power_of_two()
            || t >= assignment_vars
            || (t > log_instance_capacity && t < local_bits)
        {
            return Err(Sha256ConstraintError::UnsupportedProductSweepGeometry {
                log_compressions: log_instance_capacity,
                t,
            });
        }
        product_p_h = Some(IntegerMatrixLayout {
            row_vars: t,
            col_vars: assignment_vars - t,
            word_bits: 1,
        });
        if t > log_instance_capacity {
            product_order = PackedSourceOrder::InstanceMajor;
            layout = Sha256OpeningLayout::ProductTransposed { row_vars: t };
        }
    }
    let map = PackedRepeatedVirtualMap::new(
        local.map.clone(),
        instances,
        h_layout.cells(),
        f_layout.cells(),
    )?;
    let product_map = product_p_h
        .map(|params| {
            PackedSourceRepeatedVirtualMap::new_with_order(
                local.map.clone(),
                instances,
                params.cells(),
                f_layout.cells(),
                product_order,
            )
        })
        .transpose()?;
    let mut facts = sha256_instance_facts(exponent);
    facts.opening_t = u32::try_from(product_p_h.unwrap_or(h_layout).row_vars)
        .map_err(|_| Sha256ConstraintError::InvalidBatchExponent)?;
    if layout != Sha256OpeningLayout::Default {
        // The opening's integer lift sums `2^t` terms. The production
        // layouts keep `t <= k`; an explicit split may not, so the no-wrap
        // arity follows the larger of the two.
        facts.lift_arity_log2 = facts.lift_arity_log2.max(facts.opening_t);
    }
    let security = make_security(&facts)?;
    let prime_profile = if fixed_98 {
        Sha256PrimeProfile::fixed_98(&security, log_instance_capacity)?
    } else {
        Sha256PrimeProfile::from_security(&security, log_instance_capacity)?
    };
    Ok(PreparedSha256CompressionBatch {
        local,
        map,
        product_map,
        product_p_h,
        f_layout,
        h_layout,
        instances,
        log_instance_capacity,
        security,
        ligerito: None, // Explicit algebra fixtures omit a production PCS policy.
        prime_profile,
        opening_layout: layout,
    })
}

fn validate_batch_exponent(log_compressions: usize) -> Result<usize, Sha256ConstraintError> {
    let instances = 1usize
        .checked_shl(
            u32::try_from(log_compressions)
                .map_err(|_| Sha256ConstraintError::InvalidBatchExponent)?,
        )
        .ok_or(Sha256ConstraintError::InvalidBatchExponent)?;
    SHA256_H_INSTANCE_BITS
        .checked_mul(instances)
        .ok_or(Sha256ConstraintError::InvalidBatchExponent)?;
    Ok(instances)
}

pub(super) fn validate_instance_capacity(instances: usize) -> Result<(), Sha256ConstraintError> {
    let log_instance_capacity = instances
        .checked_next_power_of_two()
        .ok_or(Sha256ConstraintError::InvalidBatchExponent)?
        .ilog2() as usize;
    if !(SHA256_MIN_LOG_COMPRESSIONS..=SHA256_MAX_LOG_COMPRESSIONS).contains(&log_instance_capacity)
    {
        return Err(Sha256ConstraintError::UnsupportedInstanceCapacityExponent {
            actual: log_instance_capacity,
        });
    }
    Ok(())
}

fn validate_prepared_protocol(
    prepared: &PreparedSha256CompressionBatch,
) -> Result<(), Sha256ConstraintError> {
    if prepared.prime_profile.is_fixed() {
        Sha256PrimeProfile::fixed_98(&prepared.security, prepared.log_instance_capacity)?;
    } else {
        Sha256PrimeProfile::from_security(&prepared.security, prepared.log_instance_capacity)?;
    }
    let max_q_bits =
        u128::BITS as usize - prepared.security.projection_max.leading_zeros() as usize;
    let opening_params = prepared.product_p_h.as_ref().unwrap_or(&prepared.h_layout);
    let forest_count = mod_q_num_chunks(opening_params, max_q_bits);
    let single_forest_required = prepared.prime_profile.is_fixed()
        || matches!(prepared.opening_layout, Sha256OpeningLayout::Default);
    if single_forest_required && forest_count != 1 {
        return Err(Sha256ConstraintError::UnsupportedOpeningForestCount {
            actual: forest_count,
        });
    }
    let target = prepared.security.ligerito_target_bits;
    if !(64..=128).contains(&target) {
        return Err(Sha256ConstraintError::UnsupportedLigeritoTargetBits { actual: target });
    }
    Ok(())
}

pub(super) fn packed_domain_vars(
    instances: usize,
    instance_width: usize,
) -> Result<usize, Sha256ConstraintError> {
    let live = instance_width
        .checked_mul(instances)
        .and_then(|cells| cells.checked_add(1))
        .ok_or(Sha256ConstraintError::InvalidBatchExponent)?;
    let domain = live
        .checked_next_power_of_two()
        .ok_or(Sha256ConstraintError::InvalidBatchExponent)?;
    Ok(domain.ilog2() as usize)
}

/// Splits one flat binary domain across BitZ rows and columns. The semantic
/// sequence stays `[1 | instance_0 | instance_1 | ... | trailing zeros]` and
/// is stored in BitZ's physical order: low `t` bits select a packed row and
/// high `s` bits select a column. The inner sumcheck uses that same index
/// order, so its terminal equality factors directly into `2^t` row weights
/// and `2^s` column weights. Keeping both factors near `2^(vars/2)` avoids
/// materializing a `2^vars` opening vector.
pub(super) const fn balanced_binary_params(vars: usize) -> IntegerMatrixLayout {
    let t = if vars.div_ceil(2) < LOG_PACKING {
        LOG_PACKING
    } else {
        vars.div_ceil(2)
    };
    IntegerMatrixLayout {
        row_vars: t,
        col_vars: vars - t,
        word_bits: 1,
    }
}

/// Splits the derived SHA assignment so every supported runtime-prime weight
/// fits in one BitZ chunk. The current SHA profiles use at most 113-bit primes;
/// with Bit cells, `t <= 127 - 113 - 1 = 13` makes the generic fold bound
/// strictly smaller than `2^127`. Shapes already balanced below that cap keep
/// their balanced layout.
const fn single_forest_binary_params(vars: usize) -> IntegerMatrixLayout {
    let balanced = balanced_binary_params(vars);
    if balanced.row_vars <= 13 {
        balanced
    } else {
        IntegerMatrixLayout {
            row_vars: 13,
            col_vars: vars - 13,
            word_bits: 1,
        }
    }
}

/// Row variables of the balanced `Id_{2^r} ⊗ M` product layout.
///
/// The virtualization matrix of a power-of-two batch is `Id_{2^k} ⊗ M`, one
/// local block `M` per compression. Opening it instance-major with
/// `t = local_bits + r` row variables groups the batch into `2^(k-r)` blocks of
/// `Id_{2^r} ⊗ M`, i.e. `2^r` compressions per grand product: `r` instance bits
/// join the local bits on the row axis and only the remaining `k - r` instance
/// bits index columns.
///
/// Without it the split is pinned at `t = min(k, 13)` with every local cell on
/// the column axis, so the read-off vector sent in the clear grows with the
/// local width rather than with the batch. `r` is chosen to land on the same
/// balance point the rest of the instantiation uses, `t = ceil(0.6 · n)`,
/// clamped to the range this layout can represent, `r in [0, k]`.
const fn balanced_product_row_vars(
    assignment_vars: usize,
    local_bits: usize,
    log_instance_capacity: usize,
) -> usize {
    let target = (3 * assignment_vars).div_ceil(5);
    if target < local_bits {
        local_bits
    } else if target > local_bits + log_instance_capacity {
        local_bits + log_instance_capacity
    } else {
        target
    }
}

fn integer_local_relation() -> &'static IntegerLocalRelation {
    INTEGER_LOCAL_RELATION.get_or_init(|| {
        build_integer_local_relation().expect("the static SHA-256 compression relation is valid")
    })
}

fn build_integer_local_relation() -> Result<IntegerLocalRelation, Sha256ConstraintError> {
    let mut generator = ConstraintGenerator::new(COMPRESSION_INPUT_BITS);
    let inputs = generator.inputs();
    let output = compression_circuit(&mut generator, &inputs);
    let generated = generator.into_matrices();

    assert_eq!(generated.m.row_count(), SHA256_H_BAR_LIVE_BITS);
    assert_eq!(generated.m.column_count(), SHA256_F_BAR_LIVE_BITS);
    assert_eq!(generated.a.row_count(), SHA256_CONSTRAINTS);
    assert_eq!(generated.b.row_count(), SHA256_CONSTRAINTS);
    assert_eq!(generated.c.row_count(), SHA256_CONSTRAINTS);
    assert_eq!(generated.a.column_count(), SHA256_H_BAR_LIVE_BITS);
    assert_eq!(generated.b.column_count(), SHA256_H_BAR_LIVE_BITS);
    assert_eq!(generated.c.column_count(), SHA256_H_BAR_LIVE_BITS);
    assert_eq!(circuit_matrix_nnz(&generated.a), 0);
    assert_eq!(circuit_matrix_nnz(&generated.b), 0);
    assert_eq!(generated.m.row(0).unwrap().indices(), &[0]);

    for word_slot in 0..SHA256_PUBLIC_WORDS {
        for bit in 0..SHA256_PUBLIC_WORD_BITS {
            let h_column = sha256_public_h_column(word_slot, bit);
            let f_column = sha256_public_f_column(word_slot, bit);
            assert_eq!(generated.m.row(h_column).unwrap().indices(), &[f_column]);

            if word_slot >= 24 {
                let output_bit = &output[(word_slot - 24) * SHA256_PUBLIC_WORD_BITS + bit];
                assert!(!output_bit.constant());
                assert_eq!(output_bit.witnesses().len(), 1);
                assert!(output_bit.witnesses().contains(&(f_column - 1)));
            }
        }
    }

    let native_rows = convert_native_integer_rows(&generated.c)?;
    let native_matrix = CscMatrix::try_from_rows(SHA256_H_BAR_LIVE_BITS, native_rows)
        .map_err(SpartanMatrixError::from)?;
    let linear_relation = Sha256LinearRelation { native_matrix };

    let map_rows = generated
        .m
        .rows()
        .map(|row| {
            row.indices()
                .iter()
                .copied()
                .map(|column| (column, true))
                .collect::<Vec<_>>()
        })
        .collect::<Vec<_>>();
    let map = CscMatrix::try_from_rows(SHA256_F_BAR_LIVE_BITS, map_rows)
        .map_err(SpartanMatrixError::from)?;
    let map = PreparedVirtualMap::new(map)?;
    let max_boolean_residual_bound =
        max_boolean_linear_residual_bound(&linear_relation.native_matrix);
    let digest = integer_relation_digest(&linear_relation.native_matrix, &map)?;

    Ok(IntegerLocalRelation {
        linear_relation,
        map,
        digest,
        max_boolean_residual_bound,
    })
}

pub(super) fn circuit_matrix_nnz(matrix: &CsrMatrix<IntegerTable>) -> usize {
    matrix.nnz()
}

pub(super) fn convert_native_integer_rows(
    matrix: &CsrMatrix<IntegerTable>,
) -> Result<Vec<Vec<(usize, i64)>>, Sha256ConstraintError> {
    (0..matrix.row_count())
        .map(|row| {
            matrix
                .row(row)
                .unwrap()
                .iter()
                .map(|(column, coefficient)| (column, coefficient.as_words()))
                .map(|(column, words)| {
                    let value = words[0] as i64;
                    let extension = if value < 0 { u64::MAX } else { 0 };
                    if words[1..].iter().all(|&word| word == extension) {
                        Ok((column, value))
                    } else {
                        Err(Sha256ConstraintError::IntegerRelationTooLarge)
                    }
                })
                .collect::<Result<Vec<_>, _>>()
        })
        .collect()
}

#[allow(dead_code)]
fn project_signed_matrix(
    matrix: &CscMatrix<Box<[i64]>>,
    field_config: &<SpartanBitzField as crate::piop::spartan::SpartanField>::Config,
) -> Result<CscMatrix<Box<[SpartanBitzField]>>, SpartanMatrixError> {
    let field = crate::piop::spartan::raw_monty::field_context(field_config);
    let columns = matrix
        .columns()
        .map(|column| {
            column
                .into_iter()
                .map(|(row, coefficient)| (row, field.from_integer(coefficient)))
                .collect::<Vec<_>>()
        })
        .collect::<Vec<_>>();
    CscMatrix::try_from_columns(matrix.row_count(), columns).map_err(SpartanMatrixError::from)
}

pub(super) fn max_boolean_linear_residual_bound(matrix: &CscMatrix<Box<[i64]>>) -> field::Uint<2> {
    let mut sums = vec![field::Uint::<2>::ZERO; matrix.row_count()];
    for column in matrix.columns() {
        for (row, coefficient) in column {
            let next = sums[row].checked_add_ct(&field::Uint::from_u64(coefficient.unsigned_abs()));
            assert!(
                next.validity().declassify(),
                "public SHA row norm exceeds two limbs"
            );
            sums[row] = *next.value();
        }
    }
    sums.into_iter()
        .max_by_key(|value| u128::from(*value))
        .unwrap_or_default()
}

fn integer_relation_digest(
    matrix: &CscMatrix<Box<[i64]>>,
    map: &PreparedVirtualMap,
) -> Result<[u8; 32], Sha256ConstraintError> {
    let mut hash = Hasher::new();
    hash.update(b"bitz/sha256/flat-linear-relation/v3");
    hash.update(&map.digest());
    hash.update(b"C");
    for value in [matrix.row_count(), matrix.column_count(), matrix.nnz()] {
        hash_usize(&mut hash, value)?;
    }
    for column in matrix.columns() {
        hash_usize(&mut hash, column.len())?;
        for (row, coefficient) in column {
            hash_usize(&mut hash, row)?;
            hash.update(&coefficient.to_le_bytes());
        }
    }
    Ok(*hash.finalize().as_bytes())
}

pub(super) fn hash_usize(hash: &mut Hasher, value: usize) -> Result<(), Sha256ConstraintError> {
    hash.update(
        &u64::try_from(value)
            .map_err(|_| Sha256ConstraintError::IntegerRelationTooLarge)?
            .to_le_bytes(),
    );
    Ok(())
}

